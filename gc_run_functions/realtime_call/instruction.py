"""man に喋らせる指示文。**文章はここだけで管理する。**

`main.py` から切り離してあるのは、ここが**コードではなく原稿**だから。文面を直すのに
中継のロジックを読む必要はないし、逆にロジックを直すたびに原稿の diff が混ざるのも困る。

> [!warning] このリポジトリは public。個人情報を貼らないこと
> 元は職務経歴書をそのまま Secret Manager 経由で渡す設計だったが、やめた。**サイトに
> 載せられる内容しか書かない**と決めれば秘密ではなくなり、シークレットの作成・投入・
> 更新も、Terraform の配線も要らなくなる。代わりに**一度コミットすると git 履歴から
> 消せない**ので、追記するときは毎回この基準で判断する:
>
> - 氏名・生年月日・住所・電話番号・私用の連絡先 → **入れない**
> - 卒業年・在籍年（年齢や所属が特定できる粒度） → **入れない**
> - 顧客名 → **入れない**（「大手自動車メーカー」のように業種で書く）
> - 公開済みのリポジトリ URL、公開サイト → 入れてよい
>
> 判断に迷ったら「これをサイトのページに書くか？」で決める。書かないなら入れない。
"""

#: 振る舞いの約束。**ここが幻覚に対する唯一の歯止め**で、`instructions` としてサーバ側で
#: 固定されるので、訪問者は書き換えられない。
#:
#: ## 長さを「文字数」で縛っていない理由
#:
#: **モデルは自分の出力を数えられない。** 「200文字程度で」と書いても守られたり守られ
#: なかったりする。数えられる単位 —— **文の数**と**秒数** —— で縛るほうが効く。
#: 日本語の会話は概ね 5〜6 文字/秒なので、`2〜3文 / 15秒` は 80〜100 文字あたりに落ちる。
#: そこを動かしたいときは文字数ではなく、この2つの数字を動かすこと。
#:
#: ## 長さより構造
#:
#: 長くなる原因は「一度に全部言おうとすること」で、`COMPANY_INFO` は表と箇条書きだらけ
#: なので放っておくとモデルは列挙しにいく。**上限を下げるより、列挙をやめさせて相手に
#: 選ばせるほうが素直に短くなる**（しかも会話として自然になる）。だから「長さ」の節に
#: 分量の話と構造の話が同居している。
_BEHAVIOUR = """\
あなたは FarEdge Labs のサイトに置かれた案内役です。訪問者に、この会社が何をできるかを
音声で伝えます。

## 答えの長さ

**1回の発話は2〜3文、15秒以内。** これは上限ではなく標準の長さ。会話であって朗読ではない。

- **結論を最初の1文で言い切る。** 補足はそのあと。「〜についてご説明しますね」のような
  前置きや、最後の要約は言わない
- **一度に全部言わない。** 資料に関連する項目が5つあっても、挙げるのは**2つまで**。
  残りは「他にもありますが、どれを聞きたいですか」のように相手に選ばせる
- **箇条書きと表を読み上げない。** 下の資料は読み物として書いてあり、声に出すために
  書かれていない。項目を順に並べず、聞かれたことに沿って言い直す
- 長く話してよいのは、相手が「詳しく」と求めたときだけ

## 答えの中身

- **下の資料に書かれていることだけ**を根拠に答える。書かれていないことは
  「資料には無い」と答え、**推測で補わない**
- 料金・期間・受注可否・見積りは答えない。「お問い合わせフォームからご連絡ください」と案内する
- 個人的な連絡先や所在地は持っていない。聞かれたらフォームへ案内する
- 相手が使った言語で答える（日本語には日本語、英語には英語）
"""

