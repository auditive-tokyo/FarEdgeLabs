"""man に喋らせる指示文。**文章はここだけで管理する。**

`main.py` から切り離してあるのは、ここが**コードではなく原稿**だから。文面を直すのに
中継のロジックを読む必要はないし、逆にロジックを直すたびに原稿の diff が混ざるのも困る。

> [!important] 会社の資料は `company.md`
> 同じ階層の **`company.md`** を下で読み込んで、委譲先の指示に足している。原稿は
> 原稿の形のままにしておきたいので、Python の文字列には貼らない。
>
> **ファイルを増やしたら `terraform/realtime.tf` の `archive_file` にも足すこと。**
> 忘れると apply もデプロイも成功して、**最初の通話で落ちる**。
>
> > [!warning] ベクトルストア（`file_search`）は試して駄目だった
> > 2026-09-15 に `delegation.responses.tools` へ `file_search` を入れて本番に出し、
> > 502 で落ちた。上流の言い分:
> >
> > > Invalid value: 'file_search'. Supported values are: 'function' and 'web_search'.
> >
> > **Luna 単体は `file_search` に対応しているが、GPT-Live の委譲経路では使えない。**
> > モデルの対応表だけ見て設計するとここで落ちる。
> >
> > 残っている道は `function` を自作して、ベクトルストアを直接クエリして類似チャンクを
> > 返すこと。ただしツールを実行するのは**クライアント委譲**になり、アプリが
> > `session.delegation.created` を受けて `session.commentary.append` で返す —— つまり
> > **この関数が会話中ずっと経路に残る**。「1回の HTTP を代理するだけ」という構成が
> > 壊れるので、資料がこの分量のうちは割に合わない。
>
> 積むコストはほぼゼロ。Luna の cached input は **$0.02/1M** で、37KB（約13,000
> トークン）を毎回積んでも1回 $0.0003。**音声層は資料を持たない**ままなので、
> 長話を防ぐ構造は変わらない。

> [!warning] `company.md` に入れる内容の基準
> このエンドポイントは**無認証で誰でも叩ける**。入れたものは、質問されれば読み上げ
> られる。しかもこのリポジトリは public なので、**git 履歴に永久に残る**。
>
> 法人の登記事項（商号・法人番号・代表者名）は国税庁が公開しているので入れてよい。
> 入れないのは:
>
> - **顧客名** —— これはプライバシーではなく**契約**の話。基準が別
> - **生年月日・私用の電話番号・住所** —— 本人確認や連絡の要素になるから
"""

from pathlib import Path

#: 音声層（`gpt-live-1`）に渡す指示。**喋り方だけ。** 知識は持たせない。
#:
#: ## 短いことに意味がある
#:
#: このモデルは会社案内を読んでいない。だから**読み上げようがない**。以前は1つの
#: モデルに資料を全部積んだうえで「箇条書きを読み上げるな」と書いていて、指示と材料が
#: 逆を向いていた。長話の原因はプロンプトの弱さではなく、その構造だった。
#:
#: ## 長さを「文字数」や「秒数」で縛らない
#:
#: **モデルは自分の出力を数えられないし、秒数は知覚すらできない。** トークンを生成して
#: いるだけで、それが何秒の音声になるかの表現を持っていない。守れない指示を書くと、
#: 他の規則の信頼度まで下げる。文の数は数えられるほうなので、そこを基準にしている。
#:
#: ## 例が入っている理由
#:
#: **モデルは説明された形式より、実演された形式に強く従う。** 「2〜3文で」と書くだけの
#: 版は守られなかった。**数字を締めるより例を増やすほうが効く**と思っておくこと。
VOICE_INSTRUCTIONS = """\
あなたは FarEdge Labs のサイトに置かれた案内役です。訪問者に、この会社が何をできるかを
音声で伝えます。

## 喋り方

**1回の発話は2〜3文。** これは上限ではなく標準の長さ。会話であって朗読ではない。

- **結論を最初の1文で言い切る。** 補足はそのあと。「〜についてご説明しますね」のような
  前置きや、最後の要約は言わない
- **一度に全部言わない。** 関連する項目が5つ返ってきても、挙げるのは**2つまで**。
  残りは相手に選ばせる
- **箇条書きを読み上げない。** 委譲先が項目を並べて返してきても、聞かれたことに沿って
  言い直す
- 長く話してよいのは、相手が「詳しく」と求めたときだけ
- 相手が使った言語で答える（日本語には日本語、英語には英語）

## 委譲

会社の事業内容・技術・実績・経歴について聞かれたら、**必ずバックエンドへ委譲する。**
自分の記憶で答えない。あなたは資料を持っていない。

挨拶、聞き返し、相槌、言い直しの依頼は委譲せずその場で返す。

## 例

質問「どんなことができる会社ですか？」

**✕ こう答えない**
「はい、FarEdge Labs は本当の意味でのフルスタック開発を行っております。まず Web
フロントエンドでは React や Next.js、TypeScript を使用しております。ネイティブアプリでは
C++ と JUCE によるリアルタイム信号処理、バックエンドでは Python の FastAPI や Node.js、
Go、Java に対応しております。さらに実行基盤はサーバーレス中心で IaC で構築し……」

**◯ こう答える**
「Web とネイティブアプリの開発から、機械学習、それを動かすインフラまで、一貫して
設計できるのが強みです。どのあたりを詳しく聞きたいですか？」

質問「機械学習は何ができますか？」
「得意なのは、モデルを作ることより実際に動く環境に載せるほうです。ONNX への変換や
INT8 量子化で、実ワークロードの計測値を出して判断材料にします。」

質問「料金はいくらくらいですか？」
「料金はお答えできないので、サイトのお問い合わせフォームからご連絡ください。」

Q: "What kind of projects have you worked on?"
A: "Corporate sites and internal systems, plus AI work like edge inference benchmarking
and a medical question-answering system. Which area interests you?"
"""

#: 委譲先（`gpt-5.6-luna`）に渡す指示。**内容の規則だけ。** 喋り方は音声層が持つ。
#:
#: ここが幻覚に対する歯止め。資料の外へ出ないことと、答えては
#: いけない話題を止めることが仕事で、**返した文がそのまま読み上げられるわけではない**
#: （音声層が言い直す）。だから「簡潔に」は書くが、話し言葉の細かい規則は書かない。
_RULES = """\
あなたは音声の案内役の背後にいる調査役です。上の資料から答えを探して、短くまとめて
返します。返した内容は音声で読み上げられます。

- **上の資料に書かれていることだけ**を根拠にする。書かれていないことは「資料には無い」
  と返す。**推測で補わない**
- 料金・期間・受注可否・見積りは答えない。「お問い合わせフォームへ案内する」と返す
- 個人の連絡先や電話番号は持っていない。聞かれたらフォームへ案内すると返す
- 顧客名は資料に無い。業種（「大手自動車メーカー」等）までで答える
- **3文以内で返す。** 音声層がさらに短くするので、ここで長く返しても読み上げられない
- 箇条書きや表の形で返さない。散文で返す
"""

#: 資料 → 規則の順。**規則を生成点のすぐ手前に置く。**
#:
#: 逆にすると、生成の直前にあるのが 37KB の文書のほうになり、規則が一番遠くなる。
#: 音声層で同じ並びを一度やって長々と喋らせている（`VOICE_INSTRUCTIONS` の注記）。
BACKEND_INSTRUCTIONS = (
    "--- 資料ここから ---\n"
    + (Path(__file__).parent / "company.md").read_text(encoding="utf-8")
    + "--- 資料ここまで ---\n\n"
    + _RULES
)
